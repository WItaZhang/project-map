import { chromium } from 'playwright';
import { mkdir, readFile, writeFile, rename } from 'node:fs/promises';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import ffmpeg from 'ffmpeg-static';

const url = process.env.PROJECT_MAP_URL || 'http://127.0.0.1:4173/';
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
await mkdir('output/raw', { recursive: true });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 2, locale: 'zh-CN', recordVideo: { dir: 'output/raw', size: { width: 1920, height: 1080 } } });
const epoch = performance.now();
const page = await context.newPage();
page.setDefaultTimeout(30000);
const errors = [], requests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => requests.push({ url: r.url(), method: r.method() }));
try {
  await page.goto(url);
  await page.locator('[data-input="zip"]').setInputFiles(resolve('../examples/career-agent-demo.zip'));
  await page.locator('.project-name').filter({ hasText: 'career-agent-demo' }).waitFor();
  await page.locator('.filter-chip').filter({ hasText: /^全部/ }).click();
  await page.locator('[data-view="overview"]').click();
  await page.waitForTimeout(400);
  const start = (performance.now() - epoch) / 1000;
  await page.locator('[data-action="import"]').click();
  await page.locator('.import-menu [data-action="connect-github"]').click();
  await page.locator('#github-url').fill('https://github.com/WItaZhang/project-map');
  await page.waitForTimeout(600);
  await page.locator('.github-submit').click();
  await page.locator('#github-branch option[value="main"]').waitFor({ state: 'attached' });
  await page.locator('#github-branch').selectOption('main');
  await page.waitForTimeout(1600);
  await page.screenshot({ path: 'assets/screens/13a-github-branch.png' });
  await page.locator('.github-submit').click();
  await page.locator('.github-provenance:not(.hidden)').waitFor();
  assert.match(await page.locator('.github-provenance').innerText(), /WItaZhang\/project-map/);
  const revision = await page.locator('.github-revision').innerText();
  assert.match(revision, /^main · [a-f0-9]{7}$/);
  await page.waitForTimeout(900);
  await page.screenshot({ path: 'assets/screens/13-github.png' });
  const end = (performance.now() - epoch) / 1000;

  // Real refresh and source navigation are verified separately from the shot.
  const refreshCommit = page.waitForResponse(r => r.url().includes('/commits/main') && r.ok());
  await page.locator('[data-action="refresh-github"]').click();
  await refreshCommit;
  await page.locator('.github-provenance:not(.hidden)').waitFor();
  await page.waitForFunction(() => !document.querySelector('[data-action="refresh-github"]').disabled);
  await page.locator('input[aria-label="搜索对象"]').fill('src/importer.js');
  await page.locator('.object-row').filter({ hasText: 'src/importer.js' }).first().click();
  await page.locator('[data-tab="source"]').click();
  const sourceLink = page.locator('.github-source-link').first();
  assert.match(await sourceLink.getAttribute('href'), /github\.com\/WItaZhang\/project-map\/blob\/[a-f0-9]{40}\/src\/importer\.js#L\d+/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/github-cloud-mobile.png' });
  assert.deepEqual(errors, []);
  const allowed = new Set([new URL(url).origin, 'https://api.github.com', 'https://raw.githubusercontent.com']);
  assert(requests.every(r => allowed.has(new URL(r.url).origin) && ['GET', 'OPTIONS'].includes(r.method)));
  assert(!requests.some(r => /zipball|archive\/|codeload/.test(r.url)));
  const report = { url, revision, clip: { start, end, duration: end - start }, errors, requests, checks: ['real public GitHub repository', 'branch selection', 'commit-pinned source reads', 'refresh latest commit', 'GitHub source line link', 'no archive/clone request', 'GET-only source reads'] };
  await writeFile('output/github-capture-report.json', JSON.stringify(report, null, 2));
  await context.close();
  await rename(await page.video().path(), 'output/raw/github.webm');
  const duration = end - start;
  const result = spawnSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-ss', String(start), '-i', 'output/raw/github.webm', '-t', String(duration), '-vf', 'fps=30', '-c:v', 'libx264', '-preset', 'fast', '-crf', '18', '-pix_fmt', 'yuv420p', '-an', '-movflags', '+faststart', 'assets/clips/github.mp4'], { stdio: 'inherit' });
  if (result.status !== 0) throw new Error('GitHub clip encoding failed');
  const manifest = JSON.parse(await readFile('assets/clips/manifest.json', 'utf8'));
  manifest.clips = manifest.clips.filter(c => c.name !== 'github');
  manifest.clips.push({ name: 'github', start, end, duration, path: 'assets/clips/github.mp4', provenance: 'Real public GitHub API connection to WItaZhang/project-map' });
  await writeFile('assets/clips/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  console.log(JSON.stringify({ passed: true, revision, duration, requests: requests.length }));
} finally { await context.close().catch(() => {}); await browser.close(); }
